"""Copy the web app into a static website.

Showcase mode (no backend): bundle finished runs as interactive examples.

    python scripts/export_frontend.py --out ../portfolio/public/clipranker \\
        --sample runs/tire-change "Changing a tire (TVSum)" --sample runs/doc "Documentary excerpt"

Backend mode: point the page at a running ClipRanker server.

    python scripts/export_frontend.py --out site/clipranker --api https://my-server.example.com
"""

import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys_path = str(ROOT)
REPO = "https://github.com/Kshitiz726/Semantic-Video-Synthesis-with-BERT"
COLAB = "https://colab.research.google.com/github/Kshitiz726/Semantic-Video-Synthesis-with-BERT/blob/main/notebooks/ClipRanker_Colab.ipynb"


def compress(src, dst, start=None, end=None):
    """Small H.264 copy for the web. With start/end, only that span is cut (frame-accurate re-encode)."""
    import sys

    sys.path.insert(0, sys_path)
    from svs.config import ffmpeg_bin

    span = [] if start is None else ["-ss", f"{start:.3f}", "-t", f"{end - start:.3f}"]
    subprocess.run([ffmpeg_bin(), "-v", "error", "-y", *span, "-i", str(src), "-vf", "scale=-2:'min(360,ih)'",
                    "-c:v", "libx264", "-preset", "slow", "-crf", "30", "-pix_fmt", "yuv420p",
                    "-c:a", "aac", "-b:a", "64k", "-ac", "1", "-movflags", "+faststart", str(dst)], check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--api", help="backend URL (omit for showcase mode)")
    ap.add_argument("--sample", nargs=2, action="append", metavar=("RUN_DIR", "TITLE"), default=[])
    args = ap.parse_args()

    out = Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    (out / "static").mkdir(parents=True)
    src = ROOT / "app" / "static"
    shutil.copy2(src / "index.html", out / "index.html")
    for name in ("app.js", "style.css"):
        shutil.copy2(src / name, out / "static" / name)

    if args.api:
        config = f"window.CLIPRANKER_API = {json.dumps(args.api.rstrip('/'))};\n"
    else:
        samples = []
        for run_dir, title in args.sample:
            run_dir = Path(run_dir)
            sid = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
            dst = out / "samples" / sid
            (dst / "thumbs").mkdir(parents=True)
            (dst / "clips").mkdir()
            result = json.loads((run_dir / "result.json").read_text("utf-8"))
            (dst / "result.json").write_text(json.dumps(result, ensure_ascii=False, separators=(",", ":")), "utf-8")
            for thumb in (run_dir / "thumbs").glob("*.jpg"):
                shutil.copy2(thumb, dst / "thumbs" / thumb.name)
            compress(run_dir / "video.mp4", dst / "video.mp4")
            for sc in result["scenes"]:
                compress(run_dir / "video.mp4", dst / "clips" / f"scene_{sc['id']:03d}.mp4", sc["start"], sc["end"])
            samples.append({"id": sid, "name": title, "base": f"samples/{sid}/",
                            "duration": result["video"]["duration"], "n_scenes": len(result["scenes"])})
            print(f"sample {sid}: {(dst / 'video.mp4').stat().st_size / 1e6:.1f} MB video")
        shutil.copy2(ROOT / "training" / "results" / "benchmark_summary.json", out / "samples" / "benchmark.json")
        config = "window.CLIPRANKER_STATIC = " + json.dumps(
            {"samples": samples, "benchmark": "samples/benchmark.json", "repo": REPO, "colab": COLAB}, indent=1) + ";\n"
    (out / "static" / "config.js").write_text("// Generated by scripts/export_frontend.py\n" + config, "utf-8")
    print(f"Frontend written to {out}")


if __name__ == "__main__":
    main()
